// Names suppliers use that are not in Etsy's list.
const ALIASES = { 'DHL': 'dhl', 'AMAZON': 'amazon', 'AMAZON LOGISTICS': 'amazon', 'AMAZON SHIPPING': 'amazon', 'OTHER': 'other' };
const normal = value => String(value ?? '').toUpperCase().replace(/[_\s]+/g, ' ').trim();
const byName = new Map([...Object.entries(ALIASES), ...ETSY_CARRIERS.map(([name, code]) => [normal(name), code])]);
const byCode = new Map(ETSY_CARRIERS.map(([, code]) => [code, code]));
const prefixes = [...byName.keys()].sort((a, b) => b.length - a.length);

// The Etsy code for a supplier's carrier: an Etsy code ("canada-post"), a carrier
// name ("Canada Post"), or a service under it ("USPS Ground Advantage", Artelo's
// "Amazon Logistics US - Amazon Shipping Ground"; the longest name wins).
// Unknown carriers are "other", which still carries the tracking number.
export function etsyCarrierCodeFor(carrier) {
  // Names first: Etsy's "Hermes" is hermes-de, while the code "hermes" is Hermes UK.
  const name = normal(carrier);
  if (byName.has(name)) return byName.get(name);
  const raw = String(carrier ?? '').trim().toLowerCase();
  if (byCode.has(raw)) return raw;
  const prefix = prefixes.find(k => name.startsWith(k + ' '));
  return prefix ? byName.get(prefix) : 'other';
}
